export function buildNetworkArcs(sites = toyotaSites) {
  const [source, ...destinations] = sites;
  return destinations.map((site) => ({
    id: `${source.id}-${site.id}`,
    startLat: source.lat,
    startLng: source.lng,
    endLat: site.lat,
    endLng: site.lng,
    color: [source.color, site.color],
    siteId: site.id,
  }));
}
